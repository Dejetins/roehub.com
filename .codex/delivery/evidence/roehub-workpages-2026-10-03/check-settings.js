async page => {
  const root=".codex/delivery/evidence/roehub-workpages-2026-10-03";
  const checks={};
  await page.goto("http://localhost:20120/settings/profile");
  const zone=page.getByLabel("Time zone",{exact:true});
  await zone.waitFor();
  const before=await zone.inputValue(), changed=before==="UTC"?"Europe/Moscow":"UTC";
  await zone.fill(changed);
  await page.getByRole("button",{name:"Save changes",exact:true}).click();
  await page.getByText("Saved",{exact:true}).waitFor();
  await page.reload();
  await zone.waitFor();
  if(await zone.inputValue()!==changed) throw new Error("Setting did not persist");
  checks.persistence=true;
  await zone.fill(before);
  await page.getByRole("button",{name:"Save changes",exact:true}).click();
  await page.getByText("Saved",{exact:true}).waitFor();
  await page.getByLabel("Email",{exact:true}).fill("invalid");
  await page.getByRole("button",{name:"Save changes",exact:true}).click();
  await page.getByText("Enter a valid email address.",{exact:true}).waitFor();
  checks.fieldValidation=await page.getByLabel("Email",{exact:true}).getAttribute("aria-invalid")==="true";
  page.once("dialog",d=>d.dismiss());
  await page.getByRole("link",{name:"Preferences",exact:true}).click();
  checks.discardGuard=page.url().endsWith("/settings/profile");
  await page.getByRole("button",{name:"Cancel",exact:true}).click();
  await page.screenshot({path:root+"/settings-profile.png"});
  await page.getByRole("link",{name:"Preferences",exact:true}).click();
  await page.getByLabel("Table density").waitFor();
  await page.getByLabel("Language",{exact:true}).selectOption("ru");
  await page.getByRole("button",{name:"Save changes",exact:true}).click();
  await page.getByRole("heading",{name:"Предпочтения",exact:true}).waitFor();
  await page.reload();
  await page.getByRole("heading",{name:"Предпочтения",exact:true}).waitFor();
  checks.localePersisted=true;
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:root+"/settings-preferences-narrow-ru.png"});
  checks.narrow=await page.evaluate(()=>({width:innerWidth,scrollWidth:document.documentElement.scrollWidth}));
  await page.getByLabel("Язык",{exact:true}).selectOption("en");
  await page.getByRole("button",{name:"Сохранить",exact:true}).click();
  await page.getByRole("heading",{name:"Preferences",exact:true}).waitFor();
  await page.setViewportSize({width:1476,height:959});
  await page.screenshot({path:root+"/settings-preferences.png"});
  await page.getByRole("link",{name:"Security",exact:true}).click();
  await page.locator("tbody tr").first().waitFor();
  checks.sessions=await page.locator("tbody tr").count();
  await page.screenshot({path:root+"/settings-security.png"});
  await page.getByRole("tab",{name:"Activity",exact:true}).click();
  await page.locator("tbody tr").first().waitFor();
  checks.audit=true;
  await page.getByRole("link",{name:"Notifications",exact:true}).click();
  await page.getByRole("alert").waitFor();
  checks.notifications=await page.getByRole("alert").innerText();
  await page.screenshot({path:root+"/settings-notifications-unavailable.png"});
  return checks;
}
